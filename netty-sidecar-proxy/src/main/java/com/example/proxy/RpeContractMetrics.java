package com.example.proxy;

import java.util.Map;
import java.util.TreeMap;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.concurrent.atomic.AtomicLong;
import java.util.concurrent.atomic.AtomicReference;
import java.util.concurrent.atomic.LongAdder;

/**
 * The sidecar metrics contract (A3.3) read by the Admin Panel (rpe-hub) and the intelligence layer (Component 4):
 * per-hop request counts, latency, proxy overhead, in-flight requests, rejections, retries and, on the gateway, the
 * per-route chain outcomes. Every series carries the RPE service and Pod labels.
 */
final class RpeContractMetrics {
    private static final double[] BUCKETS = {0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2.5, 5, 10};
    private static final int MAX_ROUTES = 64;
    private static final String[] DIRECTIONS = {"inbound", "outbound"};
    private static final String[] OUTCOMES = {"ok", "failed", "rejected"};

    private static volatile String service = "unknown-service";
    private static volatile String pod = "unknown-pod";
    private static final Map<String, LongAdder> REQUESTS = new ConcurrentHashMap<>();
    private static final Map<String, LongAdder> ORIGINAL = new ConcurrentHashMap<>();
    private static final Map<String, LongAdder> RETRIES = new ConcurrentHashMap<>();
    private static final Map<String, LongAdder> REJECTIONS = new ConcurrentHashMap<>();
    private static final Map<String, Histogram> DURATIONS = new ConcurrentHashMap<>();
    private static final Histogram OVERHEAD = new Histogram();
    private static final AtomicLong IN_FLIGHT = new AtomicLong();
    private static final Map<String, LongAdder> CHAINS = new ConcurrentHashMap<>();
    private static final Map<String, LongAdder> CHAIN_DEADLINE = new ConcurrentHashMap<>();
    // requests forwarded unchanged because they carried no request context (no deadline / cancellation handling)
    private static final Map<String, LongAdder> PASSTHROUGH = new ConcurrentHashMap<>();

    static {
        // every series exists from the start, so rates and increases are 0 rather than missing
        for (String direction : DIRECTIONS) {
            ORIGINAL.put(direction, new LongAdder());
            PASSTHROUGH.put(direction, new LongAdder());
            DURATIONS.put(direction, new Histogram());
            for (String outcome : OUTCOMES) REQUESTS.put(direction + "|" + outcome, new LongAdder());
        }
        // the proxy does not retry yet (planned for the next phase), so retries are genuinely zero
        for (String result : new String[]{"attempted", "succeeded", "denied_budget", "denied_deadline",
                "denied_pressure", "denied_terminal"}) {
            RETRIES.put(result, new LongAdder());
        }
        for (String reason : new String[]{"expired", "insufficient_time", "overload", "invalid_context",
                "pressure_fail_fast"}) {
            REJECTIONS.put(reason, new LongAdder());
        }
    }

    private RpeContractMetrics() {}

    static void configure(String serviceName, String podName) {
        service = serviceName == null || serviceName.isBlank() ? "unknown-service" : serviceName;
        pod = podName == null || podName.isBlank() ? "unknown-pod" : podName;
    }

    /** Starts measuring one proxied request; {@code direction} is inbound or outbound. */
    static Hop begin(String direction, long startNanos) {
        IN_FLIGHT.incrementAndGet();
        return new Hop(direction, startNanos);
    }

    /** One proxied request. The first completion is recorded; later calls are ignored. */
    static final class Hop {
        private final String direction;
        private final long startNanos;
        private final AtomicBoolean done = new AtomicBoolean();
        private final AtomicReference<Runnable> onDone = new AtomicReference<>();

        private Hop(String direction, long startNanos) {
            this.direction = direction;
            this.startNanos = startNanos;
        }

        /** Runs {@code action} once when this request completes (the Component 3 per-epoch in-flight count). */
        void onComplete(Runnable action) {
            onDone.set(action);
            if (done.get()) runOnDone();
        }

        private void runOnDone() {
            Runnable action = onDone.getAndSet(null);
            if (action != null) action.run();
        }

        /** A response (from upstream or generated by the proxy) with no upstream time. */
        void complete(int status) { complete(status, 0); }

        /** A response; {@code upstreamNanos} is the time spent waiting for the upstream. */
        void complete(int status, long upstreamNanos) {
            record(status < 400 ? "ok" : status == 429 || status == 504 ? "rejected" : "failed", upstreamNanos);
        }

        /** A request the proxy rejected itself, by reason (overload, pressure_fail_fast, invalid_context, ...). */
        void reject(String reason) {
            if (record("rejected", 0)) REJECTIONS.computeIfAbsent(reason, ignored -> new LongAdder()).increment();
        }

        /** This request carried no request context and is forwarded unchanged. */
        void passthrough() {
            PASSTHROUGH.get(direction).increment();
        }

        private boolean record(String outcome, long upstreamNanos) {
            if (!done.compareAndSet(false, true)) return false;
            IN_FLIGHT.decrementAndGet();
            runOnDone();
            double total = Math.max(0, System.nanoTime() - startNanos) / 1e9;
            ORIGINAL.get(direction).increment();
            REQUESTS.computeIfAbsent(direction + "|" + outcome, ignored -> new LongAdder()).increment();
            DURATIONS.get(direction).observe(total);
            OVERHEAD.observe(Math.max(0, total - upstreamNanos / 1e9));
            return true;
        }
    }

    /** One root request completed at the gateway. Route cardinality is capped. */
    static void chain(String method, String route, boolean deadlineExceeded) {
        String key = method + " " + route;
        if (!CHAINS.containsKey(key) && CHAINS.size() >= MAX_ROUTES) key = method + " other";
        CHAINS.computeIfAbsent(key, ignored -> new LongAdder()).increment();
        LongAdder exceeded = CHAIN_DEADLINE.computeIfAbsent(key, ignored -> new LongAdder());
        if (deadlineExceeded) exceeded.increment();
    }

    static void render(StringBuilder sb) {
        String base = "service=\"" + escape(service) + "\",pod=\"" + escape(pod) + "\"";
        sb.append("# HELP rpe_requests_total Requests proxied by the RPE sidecar.\n# TYPE rpe_requests_total counter\n");
        new TreeMap<>(REQUESTS).forEach((key, value) -> {
            String[] parts = key.split("\\|", 2);
            sb.append("rpe_requests_total{").append(base).append(",direction=\"").append(parts[0])
                    .append("\",outcome=\"").append(parts[1]).append("\"} ").append(value.sum()).append('\n');
        });
        sb.append("# HELP rpe_original_requests_total First attempts (denominator for rates).\n# TYPE rpe_original_requests_total counter\n");
        new TreeMap<>(ORIGINAL).forEach((direction, value) -> sb.append("rpe_original_requests_total{").append(base)
                .append(",direction=\"").append(direction).append("\"} ").append(value.sum()).append('\n'));
        sb.append("# HELP rpe_retries_total Retry activity by result.\n# TYPE rpe_retries_total counter\n");
        new TreeMap<>(RETRIES).forEach((result, value) -> sb.append("rpe_retries_total{").append(base)
                .append(",result=\"").append(result).append("\"} ").append(value.sum()).append('\n'));
        sb.append("# HELP rpe_rejections_total Requests rejected by the proxy, by reason.\n# TYPE rpe_rejections_total counter\n");
        new TreeMap<>(REJECTIONS).forEach((reason, value) -> sb.append("rpe_rejections_total{").append(base)
                .append(",reason=\"").append(escape(reason)).append("\"} ").append(value.sum()).append('\n'));
        if (!CHAINS.isEmpty()) {
            sb.append("# HELP rpe_chain_requests_total Root requests completed at the gateway, by route.\n# TYPE rpe_chain_requests_total counter\n");
            new TreeMap<>(CHAINS).forEach((key, value) -> sb.append("rpe_chain_requests_total{").append(base)
                    .append(routeLabels(key)).append("} ").append(value.sum()).append('\n'));
            sb.append("# HELP rpe_chain_deadline_exceeded_total Root requests that exceeded their deadline, by route.\n# TYPE rpe_chain_deadline_exceeded_total counter\n");
            new TreeMap<>(CHAIN_DEADLINE).forEach((key, value) -> sb.append("rpe_chain_deadline_exceeded_total{").append(base)
                    .append(routeLabels(key)).append("} ").append(value.sum()).append('\n'));
        }
        sb.append("# HELP rpe_request_duration_seconds Per-hop latency.\n# TYPE rpe_request_duration_seconds histogram\n");
        new TreeMap<>(DURATIONS).forEach((direction, histogram) -> histogram.render(sb, "rpe_request_duration_seconds",
                base + ",direction=\"" + direction + "\""));
        sb.append("# HELP rpe_proxy_overhead_seconds Time spent inside the sidecar.\n# TYPE rpe_proxy_overhead_seconds histogram\n");
        OVERHEAD.render(sb, "rpe_proxy_overhead_seconds", base);
        sb.append("# HELP rpe_passthrough_requests_total Requests forwarded unchanged because they carried no request context.\n# TYPE rpe_passthrough_requests_total counter\n");
        new TreeMap<>(PASSTHROUGH).forEach((direction, value) -> sb.append("rpe_passthrough_requests_total{").append(base)
                .append(",direction=\"").append(direction).append("\"} ").append(value.sum()).append('\n'));
        sb.append("# HELP rpe_inflight_requests In-flight requests.\n# TYPE rpe_inflight_requests gauge\n");
        sb.append("rpe_inflight_requests{").append(base).append("} ").append(IN_FLIGHT.get()).append('\n');
        PolicyStore policies = ActivePolicy.store();
        if (policies != null) policies.render(sb, base);
    }

    private static String routeLabels(String key) {
        String[] parts = key.split(" ", 2);
        return ",method=\"" + escape(parts[0]) + "\",route=\"" + escape(parts.length > 1 ? parts[1] : "") + "\"";
    }

    private static String escape(String value) {
        return value.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n");
    }

    private static final class Histogram {
        private final LongAdder[] counts = new LongAdder[BUCKETS.length];
        private final LongAdder count = new LongAdder();
        private final LongAdder sumNanos = new LongAdder();

        Histogram() {
            for (int i = 0; i < counts.length; i++) counts[i] = new LongAdder();
        }

        void observe(double seconds) {
            for (int i = 0; i < BUCKETS.length; i++) {
                if (seconds <= BUCKETS[i]) counts[i].increment();
            }
            count.increment();
            sumNanos.add((long) (seconds * 1e9));
        }

        void render(StringBuilder sb, String name, String labels) {
            for (int i = 0; i < BUCKETS.length; i++) {
                sb.append(name).append("_bucket{").append(labels).append(",le=\"").append(BUCKETS[i]).append("\"} ")
                        .append(counts[i].sum()).append('\n');
            }
            sb.append(name).append("_bucket{").append(labels).append(",le=\"+Inf\"} ").append(count.sum()).append('\n');
            sb.append(name).append("_sum{").append(labels).append("} ").append(sumNanos.sum() / 1e9).append('\n');
            sb.append(name).append("_count{").append(labels).append("} ").append(count.sum()).append('\n');
        }
    }
}
